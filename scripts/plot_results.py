#!/usr/bin/env python3
"""Generate standalone research figures solely from recorded benchmark data.

No circuit experiments or extrapolated data are generated by this script.
Missing experiment tables skip the corresponding figure, with a manifest
entry. Run again after completing the missing experiment stage.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile

os.environ.setdefault("MPLCONFIGDIR",str(Path(tempfile.gettempdir())/"floworaclebench-mpl-cache"))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import NullFormatter
from matplotlib.lines import Line2D
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
COLORS = {"reversible_tt": "#C57435", "best": "#243B53", "walsh": "#243B53",
          "qrom": "#59879B", "selectswap": "#2A887B", "exact_formula": "#8C919A"}
NAMES = {"reversible_tt": "Reversible TT", "best": "Best implemented baseline",
         "walsh": "Walsh synthesis", "qrom": "QROM", "selectswap": "SelectSwap",
         "exact_formula": "Exact-angle formula"}
MARKERS = {"reversible_tt": "o", "best": "s", "walsh": "D", "qrom": "v",
           "selectswap": "s", "exact_formula": "."}


def style():
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 10,
        "axes.titlesize": 11, "axes.titleweight": "semibold",
        "axes.labelsize": 10, "axes.spines.top": False, "axes.spines.right": False,
        "axes.edgecolor": "#B4BBC3", "axes.linewidth": .7,
        "xtick.labelsize": 9, "ytick.labelsize": 9,
        "text.color": "#243342", "axes.labelcolor": "#243342",
        "xtick.color": "#435463", "ytick.color": "#435463",
        "legend.frameon": False, "legend.fontsize": 8.5,
        "lines.linewidth": 1.7, "lines.markersize": 5,
        "savefig.facecolor": "white", "figure.facecolor": "white",
        "pdf.fonttype": 42, "ps.fonttype": 42, "svg.fonttype": "none",
        "svg.hashsalt": "FlowOracleBench-0.1.0",
    })


def numeric(value):
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (ValueError, TypeError):
        return value


def load_csv(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    with path.open(newline="") as file:
        return [{key: numeric(value) for key,value in row.items()} for row in csv.DictReader(file)]


def panel(ax, title, xlabel, ylabel, *, logx=False, logy=False):
    ax.set_title(title, loc="left", pad=11)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if logx:
        ax.set_xscale("log")
    if logy:
        ax.set_yscale("log")
    ax.grid(axis="y", which="major", color="#CFD5DC", alpha=.55, linewidth=.6)
    ax.set_axisbelow(True)


def line(ax, rows, x, y, method, *, label=None, linestyle="-", alpha=1., marker=None):
    rows = sorted([r for r in rows if r.get(x) is not None and r.get(y) is not None], key=lambda r:r[x])
    if not rows:
        return
    ax.plot([r[x] for r in rows], [r[y] for r in rows], color=COLORS[method],
            marker=marker or MARKERS[method], linestyle=linestyle, alpha=alpha,
            label=label or NAMES[method])


def minimum_by(rows, keys):
    out = {}
    for row in rows:
        key = tuple(row[k] for k in keys)
        if key not in out or row["t_count_estimate"] < out[key]["t_count_estimate"]:
            out[key] = row
    return list(out.values())


def save_figure(fig, stem, output, inputs, manifest, note):
    output.mkdir(parents=True, exist_ok=True)
    files = []
    for extension in ("png", "pdf", "svg"):
        path = output / f"{stem}.{extension}"
        metadata = {"Creator": "FlowOracleBench"}
        if extension == "pdf":
            metadata.update({"CreationDate": None, "ModDate": None})
        fig.savefig(path, dpi=180, bbox_inches="tight", metadata=metadata)
        files.append(str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path))
    plt.close(fig)
    sources = []
    for path in inputs:
        sources.append({"file": str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
                        "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    manifest["figures"].append({"name":stem, "files":files, "inputs":sources, "interpretation":note})
    print(f"Wrote {stem}: PNG, PDF, SVG")


def oracle_figure(results, output, manifest):
    precision_path = results/"precision.csv"
    portfolio_path = results/"baseline_portfolio.csv"
    matched_path = results/"matched.csv"
    precision, portfolio, matched = map(load_csv,(precision_path,portfolio_path,matched_path))
    if not precision or not portfolio or not matched:
        manifest["skipped"].append({"figure":"oracle_error_resources","reason":"missing precision, portfolio, or matched table"})
        return
    fig, axes = plt.subplots(1,2,figsize=(10.6,3.85))
    ax = axes[0]
    choices = [(2,4,"--","o"),(2,8,"-","o"),(4,4,"--","s"),(4,8,"-","s")]
    for rank,n,linestyle,marker in choices:
        rows=[r for r in precision if r["dataset"]==f"gmm_2d_rank{rank}" and r["grid"]==n]
        if not rows:
            continue
        rows=sorted(rows,key=lambda r:r["t_count_estimate"])
        ax.plot([r["t_count_estimate"] for r in rows],[r["operator_error"] for r in rows],
                color=COLORS["reversible_tt"] if rank==4 else COLORS["walsh"],
                linestyle=linestyle,marker=marker,markerfacecolor="white" if n==4 else None,
                label=f"Rank {rank}, {n}×{n} grid")
    panel(ax,"A  TT arithmetic precision sweep","Estimated logical T count",
          "Measured phase-oracle operator error",logx=True,logy=True)
    ax.legend(loc="lower left",fontsize=8)
    ax.text(.98,.98,"Learned 2D potentials\nRotation budget = 10⁻⁴",
            transform=ax.transAxes,ha="right",va="top",fontsize=8,color="#697480")

    ax=axes[1]
    target="gmm_2d_rank4"; grid=8
    candidates=[r for r in portfolio if r["dataset"]==target and r["grid"]==grid]
    candidates=minimum_by(candidates,["method","tolerance"])
    candidates += [r for r in matched if r["dataset"]==target and r["grid"]==grid and r["method"]=="reversible_tt"]
    for method in ("reversible_tt","walsh","qrom","selectswap"):
        line(ax,[r for r in candidates if r["method"]==method],"tolerance","t_count_estimate",method)
    panel(ax,"B  Matched target accuracy","Total operator-error target",
          "Estimated logical T count",logx=True,logy=True)
    ticks=sorted({r["tolerance"] for r in candidates},reverse=True)
    if ticks:
        ax.set_xticks(ticks,[f"{v:g}" for v in ticks])
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.set_xlim(max(ticks)*1.4,min(ticks)/1.4)
    ax.legend(loc="center left",fontsize=8)
    ax.text(.02,.98,"Rank 4, 8×8 learned grid\nSelectSwap: best bank size per target",
            transform=ax.transAxes,ha="left",va="top",fontsize=8,color="#697480")
    fig.subplots_adjust(left=.075,right=.985,bottom=.21,top=.90,wspace=.35)
    fig.text(.075,.035,"Phase errors are measured before rotation synthesis. T counts use the stated synthesis model; panel B allocates half the target to synthesis.",fontsize=8,color="#697480")
    save_figure(fig,"oracle_error_resources",output,[precision_path,portfolio_path,matched_path],manifest,
                "Panel A uses the recorded fixed 1e-4 rotation budget. Panel B compares identical total error targets with tolerance/2 synthesis allowance; SelectSwap is minimized over implemented bank sizes. T counts are estimates, not executed synthesis.")


def scaling_figure(results,output,manifest):
    scaling_path=results/"scaling.csv";portfolio_path=results/"scaling_portfolio.csv";matched_path=results/"matched.csv"
    scaling,portfolio,matched=map(load_csv,(scaling_path,portfolio_path,matched_path))
    if not scaling or not portfolio or not matched:
        manifest["skipped"].append({"figure":"scaling_resources","reason":"missing scaling, scaling portfolio, or learned matched table"})
        return
    fig,axes=plt.subplots(2,2,figsize=(10.6,7.1))
    tt=[r for r in scaling if r["method"]=="reversible_tt"]
    best=minimum_by(portfolio,["dataset","tolerance"])
    nominal_tolerance=min({r["tolerance"] for r in tt},key=lambda v:abs(v-.01))
    tt=[r for r in tt if r["tolerance"]==nominal_tolerance]
    best=[r for r in best if r["tolerance"]==nominal_tolerance]
    for method,rows in [("reversible_tt",tt),("best",best)]:
        filtered=[r for r in rows if r["dimension"]==4 and r["grid"]==4]
        line(axes[0,0],filtered,"rank","t_count_estimate",method)
    panel(axes[0,0],"A  Synthetic rank sweep: d = 4, N = 4","TT bond cap","Estimated logical T count",logy=True)
    axes[0,0].set_xticks(sorted({r["rank"] for r in tt if r["dimension"]==4 and r["grid"]==4}))
    axes[0,0].legend(loc="upper left",fontsize=8)

    learned=[r for r in matched if r["dataset"]=="gmm_2d_rank4" and r["tolerance"]==nominal_tolerance]
    for method,rows in [("reversible_tt",[r for r in learned if r["method"]=="reversible_tt"]),
                        ("best",[r for r in learned if r["method"]!="reversible_tt"])]:
        line(axes[0,1],rows,"grid","t_count_estimate",method)
    panel(axes[0,1],"B  Learned resolution sweep: d = 2, rank 4","Grid points per coordinate, N","Estimated logical T count",logy=True)
    axes[0,1].set_xticks(sorted({r["grid"] for r in learned}))

    for method,rows in [("reversible_tt",tt),("best",best)]:
        line(axes[1,0],[r for r in rows if r["rank"]==1 and r["grid"]==4],"dimension","t_count_estimate",method)
    panel(axes[1,0],"C  Synthetic dimension sweep: rank 1, N = 4","Spatial dimension, d","Estimated logical T count",logy=True)
    axes[1,0].set_xticks(sorted({r["dimension"] for r in tt if r["rank"]==1 and r["grid"]==4}))

    # Comparable cost panels share one y range; no extrapolated crossover line.
    relevant=[r for r in tt+best+learned if r.get("t_count_estimate")]
    lower=min(r["t_count_estimate"] for r in relevant)*.65
    upper=max(r["t_count_estimate"] for r in relevant)*1.7
    for ax in [axes[0,0],axes[0,1],axes[1,0]]:
        ax.set_ylim(lower,upper)
    largest=max(tt,key=lambda r:(r["dimension"],r["grid"],-r["rank"]))
    rowset=[r for r in portfolio if r["dataset"]==largest["dataset"] and r["tolerance"]==nominal_tolerance]
    ax=axes[1,1]
    for method in ("walsh","qrom","selectswap"):
        rows=sorted([r for r in rowset if r["method"]==method],key=lambda r:r["logical_qubits"])
        line(ax,rows,"logical_qubits","t_count_estimate",method,
             linestyle="-" if method=="selectswap" else "None",label=NAMES[method])
    line(ax,[largest],"logical_qubits","t_count_estimate","reversible_tt",linestyle="None")
    panel(ax,f"D  Space–T tradeoff: synthetic d = {int(largest['dimension'])}, rank {int(largest['rank'])}",
          "Logical qubits","Estimated logical T count",logx=True,logy=True)
    ax.legend(loc="upper right",fontsize=8)
    fig.subplots_adjust(left=.075,right=.985,bottom=.13,top=.94,wspace=.35,hspace=.46)
    fig.text(.075,.055,f"All panels: total error target {nominal_tolerance:g}, half allocated to rotation synthesis. Baseline = lowest T count among implemented Walsh, QROM and SelectSwap circuits.",fontsize=8,color="#697480")
    fig.text(.075,.028,"Synthetic and learned potentials are separated. Lines connect measured configurations; no quantum advantage or asymptotic crossover is inferred.",fontsize=8,color="#697480")
    save_figure(fig,"scaling_resources",output,[scaling_path,portfolio_path,matched_path],manifest,
                "Rank and dimension sweeps are controlled synthetic cases. Resolution sweep uses the learned rank-four 2D checkpoint. Panel D retains all implemented SelectSwap space/T variants; no extrapolation.")


def evolution_figure(results,output,manifest):
    path=results/"evolution.csv";rows=load_csv(path)
    if not rows:
        manifest["skipped"].append({"figure":"end_to_end","reason":"evolution.csv not yet present or empty"})
        return
    required={"method","grid","steps","fidelity","tv_distance","t_count_estimate","logical_qubits"}
    if not required <= set(rows[0]):
        manifest["skipped"].append({"figure":"end_to_end","reason":"evolution.csv missing columns: "+", ".join(sorted(required-set(rows[0])))})
        return
    config_path=results/"config.json"
    if config_path.is_file():
        expected=json.loads(config_path.read_text()).get("evolution",{})
        cases={(n,s) for n in expected.get("grids",[]) for s in expected.get("steps",[])}
        observed={(r["grid"],r["steps"]) for r in rows}
        if cases and not cases <= observed:
            manifest["skipped"].append({"figure":"end_to_end","reason":f"evolution is still running: {len(observed & cases)}/{len(cases)} configured grid/step cases recorded"})
            return
    grids=sorted({int(r["grid"]) for r in rows})[:2]
    if any(len({r["steps"] for r in rows if r["grid"]==n}) < 2 for n in grids):
        manifest["skipped"].append({"figure":"end_to_end","reason":"evolution sweep currently has fewer than two step counts per grid; avoiding a partial convergence figure"})
        return
    fig,axes=plt.subplots(len(grids),2,figsize=(10.6,3.35*len(grids)+.6),squeeze=False,sharey="col")
    for index,n in enumerate(grids):
        for method in ("reversible_tt","walsh","selectswap","exact_formula"):
            selected=[dict(r) for r in rows if r["grid"]==n and r["method"]==method]
            for r in selected:
                r["infidelity"]=max(1-r["fidelity"],1e-15)
            line(axes[index,0],selected,"steps","infidelity",method,
                 linestyle="--" if method=="exact_formula" else "-",alpha=.9)
            if method!="exact_formula":
                line(axes[index,1],selected,"steps","t_count_estimate",method)
        panel(axes[index,0],f"{chr(65+index*2)}  {n}×{n} grid: error to numerical evolution",
              "Commutator formula steps","Measured state infidelity, 1 − F",logx=True,logy=True)
        panel(axes[index,1],f"{chr(66+index*2)}  {n}×{n} grid: complete evolution cost",
              "Commutator formula steps","Estimated logical T count",logx=True,logy=True)
        ticks=sorted({r["steps"] for r in rows if r["grid"]==n})
        for ax in axes[index]:
            ax.set_xticks(ticks,[str(int(t)) for t in ticks])
            ax.xaxis.set_minor_formatter(NullFormatter())
        if index==0:
            axes[index,0].legend(loc="best",fontsize=8)
            axes[index,1].legend(loc="best",fontsize=8)
    fig.subplots_adjust(left=.075,right=.985,bottom=.24 if len(grids)==1 else .14,top=.94,wspace=.35,hspace=.47)
    fig.text(.075,.048,"State errors use exact rotation angles and the same learned finite-grid Hamiltonian. T costs include the modelled synthesis allowance; no hardware was executed.",fontsize=8,color="#697480")
    fig.text(.075,.023,"Overlapping error curves are expected when product-formula error dominates. Infidelity values below 10⁻¹⁵ are displayed at 10⁻¹⁵.",fontsize=8,color="#697480")
    save_figure(fig,"end_to_end",output,[path]+([config_path] if config_path.is_file() else []),manifest,
                "Measured state infidelity against dense numerical evolution, using exact circuit angles, alongside estimated complete-circuit T counts. Infidelity display floor1e-15; raw fidelity and TV remain in evolution.csv.")


def training_figure(output,manifest):
    inputs=[]
    fig,axes=plt.subplots(1,2,figsize=(10.6,3.75))
    qualities={}
    for rank,method in [(2,"walsh"),(4,"reversible_tt")]:
        stem=ROOT/"data/checkpoints"/f"gmm_2d_rank{rank}"
        loss_path=stem.with_suffix(".losses.csv");quality_path=stem.with_suffix(".quality.json")
        if not loss_path.is_file() or not quality_path.is_file():
            plt.close(fig)
            manifest["skipped"].append({"figure":"training_quality","reason":"training loss or quality file absent"})
            return
        inputs.extend([loss_path,quality_path])
        losses=load_csv(loss_path)
        training=np.asarray([r["loss"] for r in losses if r["kind"]=="train"])
        window=100
        average=np.convolve(training,np.ones(window)/window,mode="valid")
        axes[0].plot(np.arange(window,len(training)+1),average,color=COLORS[method],label=f"Rank {rank}")
        qualities[rank]=json.loads(quality_path.read_text())
    panel(axes[0],"A  Public JAM training","Optimization step","Training loss, 100-step moving mean")
    axes[0].legend(loc="upper right")
    labels=["Initial source","Rank 2 ODE","Rank 4 ODE","Target–target"]
    values=[qualities[2]["source_target_sw1"],qualities[2]["learned_ode_target_sw1"],
            qualities[4]["learned_ode_target_sw1"],qualities[4]["target_target_sw1_sample_floor"]]
    bars=axes[1].bar(np.arange(4),values,color=["#AEB8C2",COLORS["walsh"],COLORS["reversible_tt"],COLORS["selectswap"]],width=.63)
    axes[1].set_xticks(np.arange(4),labels,rotation=0,fontsize=8)
    for bar,value in zip(bars,values):
        axes[1].text(bar.get_x()+bar.get_width()/2,value+.02,f"{value:.3f}",ha="center",fontsize=9)
    panel(axes[1],"B  Independent classical quality diagnostic","","Sliced 1-Wasserstein to target")
    axes[1].set_ylim(0,max(values)*1.17)
    fig.subplots_adjust(left=.075,right=.985,bottom=.22,top=.89,wspace=.34)
    fig.text(.075,.06,"2D Gaussian-mixture target; one training seed, 2,048 diagnostic particles, 200 projection directions. ODE results are classical training diagnostics.",fontsize=8,color="#697480")
    fig.text(.075,.025,"Rank-two particle trajectories have not converged under RK4 refinement. See training_and_data.md for periodic-domain and interpolation limitations.",fontsize=8,color="#697480")
    save_figure(fig,"training_quality",output,inputs,manifest,
                "Recorded training loss (100-step trailing mean) and independent measured classical particle-ODE SW1 diagnostics, one seed. No error bars or convergence claim; rank-two refinement limitation explicit.")


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--results",type=Path,default=ROOT/"results")
    parser.add_argument("--output",type=Path,default=ROOT/"figures")
    parser.add_argument("--skip-training",action="store_true")
    args=parser.parse_args()
    style()
    manifest={"generated_at_utc":datetime.now(timezone.utc).isoformat(),
              "script":"scripts/plot_results.py", "matplotlib":matplotlib.__version__,
              "data_policy":"Only recorded input rows; no fabricated points, extrapolation, or unexecuted experiment claims.",
              "figures":[],"skipped":[]}
    oracle_figure(args.results,args.output,manifest)
    scaling_figure(args.results,args.output,manifest)
    evolution_figure(args.results,args.output,manifest)
    if not args.skip_training:
        training_figure(args.output,manifest)
    args.output.mkdir(parents=True,exist_ok=True)
    (args.output/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    for skipped in manifest["skipped"]:
        for extension in ("png","pdf","svg"):
            (args.output/f"{skipped['figure']}.{extension}").unlink(missing_ok=True)
        print(f"Skipped {skipped['figure']}: {skipped['reason']}")


if __name__=="__main__":
    main()
